#!/usr/bin/env node
// Bundle the Layer-3 attack-path records into tools/data/path-corpus.js — the default
// dataset of the Path Atlas and the tools built on it.
//
// A <script src> file rather than JSON: browsers block fetch() for pages opened from
// disk, and the tools must work straight from a clone.
//
// Deterministic (records sorted by file, a content hash instead of a timestamp), so the
// output only changes when a record does; `npm run validate` rebuilds it and a stale
// bundle shows up as a git diff, the same pattern as build-okf.
//
// Usage: node scripts/build-path-corpus.js
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'tools', 'data', 'path-corpus.js');
const SOURCES = [
  { dir: 'attack-paths', source: 'repo' },
  { dir: 'json-schemas/layer-3/examples', source: 'example' },
];

const DICTS = fs.readdirSync(path.join(ROOT, 'json-schemas/layer-1'))
  .map((f) => /^tlctc-framework\.v(\d+)\.(\d+)\.json$/.exec(f)).filter(Boolean)
  .sort((a, b) => (+a[1] - +b[1]) || (+a[2] - +b[2]));
const dictFile = DICTS[DICTS.length - 1][0];
const dict = require(path.join(ROOT, 'json-schemas/layer-1', dictFile));

const records = [];
for (const { dir, source } of SOURCES) {
  for (const f of fs.readdirSync(path.join(ROOT, dir)).filter((x) => x.endsWith('.json')).sort()) {
    const rel = `${dir}/${f}`;
    let j;
    try { j = JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); } catch (e) {
      console.error(`build-path-corpus: ${rel} does not parse: ${e.message}`); process.exit(1);
    }
    if (!Array.isArray(j.path_sequence)) { console.error(`build-path-corpus: ${rel} has no path_sequence`); process.exit(1); }
    const m = j.metadata || {};
    records.push({
      file: rel, source,
      metadata: { incident_id: m.incident_id || null, analyst_confidence: m.analyst_confidence || null, tlctc_version: m.tlctc_version || null },
      path_sequence: j.path_sequence,
    });
  }
}

const body = JSON.stringify(records);
const corpus = {
  schema: 'tlctc-path-corpus.v1',
  corpus_hash: crypto.createHash('sha256').update(body).digest('hex'),
  tlctc_version: dict.metadata.tlctc_version,
  dictionary: dictFile,
  clusters: Object.fromEntries(Object.entries(dict.clusters).map(([id, c]) => [id, c.name])),
  records,
};

const text = '// GENERATED by scripts/build-path-corpus.js from attack-paths/ and json-schemas/layer-3/examples/ — do not edit.\n'
  + `window.TLCTC_PATH_CORPUS = ${JSON.stringify(corpus)};\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (prev !== text) fs.writeFileSync(OUT, text, 'utf8');
const bySource = records.reduce((a, r) => ((a[r.source] = (a[r.source] || 0) + 1), a), {});
console.log(`build-path-corpus: ${prev === text ? 'unchanged' : 'wrote'} tools/data/path-corpus.js — ${records.length} records (${Object.entries(bySource).map(([k, v]) => `${k} ${v}`).join(', ')}), hash ${corpus.corpus_hash.slice(0, 8)}, ${Math.round(text.length / 1024)} KB`);
