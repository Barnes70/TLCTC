#!/usr/bin/env node
// Generate tools/data/tlctc-canon.js — the cluster canon and rule statements, verbatim from the
// current dictionary, for tools that quote them (the Classification Trainer's feedback).
//
// Generated rather than hand-copied: a hand-copied cluster table is how tools drifted from the
// canon before (CBP's pre-v2.3.1 #4, the Radar's "#8 … facilities"). `npm run validate`
// rebuilds it, so a dictionary change reaches the tools and shows up as a git diff.
//
// Usage: node scripts/build-tool-canon.js
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'tools', 'data', 'tlctc-canon.js');
const DICTS = fs.readdirSync(path.join(ROOT, 'json-schemas/layer-1'))
  .map((f) => /^tlctc-framework\.v(\d+)\.(\d+)\.json$/.exec(f)).filter(Boolean)
  .sort((a, b) => (+a[1] - +b[1]) || (+a[2] - +b[2]));
const dictFile = DICTS[DICTS.length - 1][0];
const dict = require(path.join(ROOT, 'json-schemas/layer-1', dictFile));

const canon = {
  schema: 'tlctc-canon.v1',
  tlctc_version: dict.metadata.tlctc_version,
  dictionary: dictFile,
  clusters: Object.fromEntries(Object.entries(dict.clusters).map(([id, c]) => [id, {
    name: c.name, definition: c.definition, generic_vulnerability: c.generic_vulnerability,
    attackers_view: c.attackers_view, topology: c.topology,
  }])),
  rules: Object.fromEntries(dict.rules.map((r) => [r.rule_id, r.statement])),
};

const text = `// GENERATED by scripts/build-tool-canon.js from json-schemas/layer-1/${dictFile} — do not edit.\n`
  + `window.TLCTC_CANON = ${JSON.stringify(canon, null, 1)};\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (prev !== text) fs.writeFileSync(OUT, text, 'utf8');
console.log(`build-tool-canon: ${prev === text ? 'unchanged' : 'wrote'} tools/data/tlctc-canon.js — ${Object.keys(canon.clusters).length} clusters, ${Object.keys(canon.rules).length} rules from ${dictFile}`);
